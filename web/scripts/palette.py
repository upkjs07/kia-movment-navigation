"""
모래시계 색. 레퍼런스 사진에서 가져오는 건 '자리'(어디가 두껍고 어디서 꺾이는지)뿐이고
색은 여기서 정한다.

좌우를 일부러 다르게 둔다. 같은 계열을 양쪽에 쓰면 데칼코마니처럼 보인다.

  왼쪽  — 원본 레퍼런스 왼쪽 잎에서 그대로 잰 배색. 붉은 심지가 자주빛으로 가라앉았다가
          청록 고리에서 환해지고 다시 보라로 떨어진다. 이 명도의 오르내림이 재미의
          출처라, 명도를 따로 손대지 않는다 — 잰 색에 이미 들어 있다.
  오른쪽 — 통째로 주황 계열. 노란 심지에서 주황·산호를 지나 크림빛으로 옅어진다.
          보라·파랑으로 넘어가지 않게 두는 것이 요점이다.

둘 다 p=0(허리)에서는 같은 색이어야 한다. 두 잎이 거기서 만나므로 색이 다르면 가운데
세로 경계가 생긴다. 그래서 같은 심지색 CORE 에서 출발한다.

섞는 일은 전부 OKLab 에서 한다. sRGB 에서 여러 색을 평균 내면 회색 쪽으로 끌려가
탁해지는데, 셰이더가 덩어리 스물넷을 한꺼번에 섞으므로 특히 그렇다.

동심원은 공짜로 나온다. 팔레트를 타는 값 p 를 '허리에서 멀어진 정도' 와 '중심선에서
멀어진 정도' 를 섞어 만들면, 잎 좌표에서 자연히 겹겹의 고리가 된다.
"""

def _hex(s):
    return (int(s[1:3], 16) / 255, int(s[3:5], 16) / 255, int(s[5:7], 16) / 255)

# ── 색 공간 ────────────────────────────────────────────────────────────────────

def _to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

def _to_srgb(c):
    c = max(0.0, c)
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055

def srgb_to_oklab(rgb):
    r, g, b = (_to_linear(c) for c in rgb)
    l = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return (0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s)

def oklab_to_srgb(lab):
    L, A, B = lab
    l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3
    m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3
    s = (L - 0.0894841775 * A - 1.2914855480 * B) ** 3
    return tuple(min(1.0, max(0.0, _to_srgb(v))) for v in (
        +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s))

def _in_gamut(lab, eps=1e-4):
    L, A, B = lab
    l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3
    m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3
    s_ = (L - 0.0894841775 * A - 1.2914855480 * B) ** 3
    for v in (+4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s_,
              -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s_,
              -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s_):
        if v < -eps or v > 1 + eps:
            return False
    return True

def _saturate(lab, amount=1.0):
    """색상과 명도는 그대로 두고 채도만 sRGB 색영역 경계까지 민다.
       그 색상·그 명도에서 낼 수 있는 최대 채도가 경계값이다. amount 로 조절한다."""
    L, A, B = lab
    c = (A * A + B * B) ** 0.5
    if c < 1e-6:
        return lab
    ua, ub = A / c, B / c
    lo, hi = c, 0.5                       # 위로 이분 탐색
    if _in_gamut((L, ua * hi, ub * hi)):
        cmax = hi
    else:
        for _ in range(28):
            mid = (lo + hi) / 2
            if _in_gamut((L, ua * mid, ub * mid)): lo = mid
            else: hi = mid
        cmax = lo
    c2 = c + (cmax - c) * amount
    return (L, ua * c2, ub * c2)

def _ramp(stops, t):
    """OKLab 에서 보간한다 — sRGB 로 하면 중간이 탁해진다."""
    t = max(0.0, min(1.0, t))
    for i in range(len(stops) - 1):
        (p0, c0), (p1, c1) = stops[i], stops[i + 1]
        if t <= p1 or i == len(stops) - 2:
            f = 0.0 if p1 <= p0 else (t - p0) / (p1 - p0)
            f = max(0.0, min(1.0, f))
            a, b = srgb_to_oklab(c0), srgb_to_oklab(c1)
            return _saturate(tuple(x + (y - x) * f for x, y in zip(a, b)), SATURATE)
    return _saturate(srgb_to_oklab(stops[-1][1]), SATURATE)

SATURATE = 1.0                  # 1.0 = 색영역 경계까지 (그 색상·명도의 최대 채도)

# ── 팔레트 ────────────────────────────────────────────────────────────────────

CORE = _hex("#FF8A33")          # 허리의 심지. 좌우가 반드시 공유한다.

# 왼쪽 — 레드 → 퍼플 → 밝은 하늘색. 원본 레퍼런스 왼쪽 잎의 성격이다.
# 하늘색은 한 점이 아니라 구간으로 둔다. 점으로 두면 덩어리 평균에 묻혀 사라지고,
# 너무 넓히면 바깥 보라 띠를 덮어 버린다 — 0.66‥0.78 이 그 사이다.
LEFT = [(0.00, CORE),            (0.14, _hex("#D4503A")), (0.28, _hex("#C32F3C")),
        (0.40, _hex("#9A2A72")), (0.52, _hex("#7E2A86")), (0.60, _hex("#6B3BC8")),
        (0.66, _hex("#7FD0EA")), (0.78, _hex("#7FD0EA")), (0.88, _hex("#6A2EC8")),
        (1.00, _hex("#4B2396"))]

# 오른쪽 — Q2 의 채도 높은 주황·핑크. 파랑·보라는 넣지 않는다. 양쪽이 다 바깥에서
# 파랑으로 끝나면 좌우가 구분되지 않는다.
# 전에 흰색을 섞고 끝을 연분홍으로 뒀더니 전체가 들떠서, 섞지 않고 바깥을 짙게 둔다.
# 흰 기운은 아래 쐐기가 맡는다 — 전면에 깔지 않아야 '살짝' 으로 읽힌다.
# 주황을 넓게 깔고 핑크는 바깥 테두리로 민다. p 에서의 비율과 화면 면적은 다르다 —
# 잎이 바깥으로 갈수록 넓어져서 큰 p 가 픽셀을 훨씬 많이 먹는다. 그래서 주황을
# 0.7 근처까지 끌고 가야 주황이 주인이 된다.
RIGHT = [(0.00, CORE),            (0.28, _hex("#FF7A20")), (0.55, _hex("#FF6A1E")),
         (0.72, _hex("#FF5C50")), (0.85, _hex("#FF4D7A")), (0.94, _hex("#F5329A")),
         (1.00, _hex("#D92A86"))]

U_W, V_W = 0.78, 0.34           # p 를 만들 때 가로·세로가 기여하는 비중

def colour_at(u, v):
    """부호 있는 u(-1 왼쪽 끝 ‥ 0 허리 ‥ +1 오른쪽 끝) 와 v(0 중심선 ‥ 1 경계).
       돌려주는 값은 OKLab 이다 — 셰이더가 그대로 섞는다."""
    p = abs(u) * U_W + max(0.0, v) * V_W
    return _ramp(LEFT if u < 0 else RIGHT, max(0.0, min(1.0, p)))

# ── 오른쪽 잎의 옅은 쐐기 ──────────────────────────────────────────────────────
# 원본 레퍼런스에서 흰 기운(min/max)을 재 보면 대각선 능선이다:
#   u=0.10 → v≈0.66,  u=0.20 → v≈0.55,  u=0.30 → v≈0.41,  u=0.45 → v≈0.31
# 허리 근처에서 가장 희고 u≈0.6 쯤 사라진다. 허리에서 부채처럼 퍼지는 모양이라
# p 하나로는 안 나온다 — 그래서 능선 위에 덩어리를 따로 얹는다. v 는 중심선에서의
# 거리라, 하나만 놓아도 위아래 두 줄기로 나타난다.
CREAM = _hex("#FFF4E6")
STREAK = [
    # (u, v, 반경u, 반경v, 크림을 섞는 정도)
    (0.10, 0.66, 0.11, 0.15, 0.55),
    (0.20, 0.55, 0.12, 0.15, 0.50),
    (0.32, 0.41, 0.13, 0.15, 0.38),
    (0.46, 0.31, 0.14, 0.16, 0.26),
]

def streak_blobs():
    cream = srgb_to_oklab(CREAM)
    out = []
    for u, v, ru, rv, amt in STREAK:
        base = colour_at(u, v)
        out.append((u, v, ru, rv) + tuple(b + (c - b) * amt for b, c in zip(base, cream)))
    return out
